# -*- coding: utf-8 -*-
"""Assemble the Korean patch from the translated chunks.

  python build_mod.py            # collect -> apply -> compile -> stage mod/
  python build_mod.py --install  # ...and copy the staged files into the game

Only additive files are produced; the original *.rpa archives are never touched.
"""
import os, sys, io, json, shutil, subprocess

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

W = os.environ.get("OBE_WORKSPACE") or os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOOLS = os.path.join(W, "tools")
WORK = os.path.join(W, "work")
CHUNKS = os.path.join(WORK, "chunks")
TL_SRC = os.path.join(W, "tl_korean")
PROJ = os.path.join(W, "proj")
PROJ_TL = os.path.join(PROJ, "game", "tl", "korean")
MOD_SRC = os.path.join(W, "mod_src")
IMG_SRC = os.path.join(W, "이미지번역", "번역본")   # optional: tl/korean/... image tree
# 11-20 update images: tl/korean replacements (override IMG_SRC) and new shared buttons
UPD_IMG = os.path.join(W, "이미지번역", "03_업데이트_1120")
VID_SRC = os.path.join(W, "영상번역", "번역본")     # optional: images/*.webm with Korean subtitles
UI_KO = os.path.join(WORK, "ui_korean.json")       # Korean UI catalog (tools/ui_catalog.py build)
# new buttons the language screen / title screen need for the fifth language
KOR_BUTTONS = [f"gui/localization/sys_data_language_bo1_kor_{s}.png" for s in ("normal", "click", "confim")] + [
    "gui/localization/title_language_kor_normal.png",
    "gui/localization/title_language_kor_click.png",
    "gui/localization/title_language_custom_kor_normal.png",
]
STAGE = os.path.join(W, "mod")
GAME = os.environ.get("OBE_GAME_DIR") or (
    r"C:\Program Files (x86)\Steam\steamapps\common\永恒与星辰与日常\game")

sys.path.insert(0, TOOLS)
import units as U


def run(*args, cwd=None):
    p = subprocess.run(args, cwd=cwd, capture_output=True, text=True,
                       encoding="utf-8", errors="replace")
    if p.stdout:
        print(p.stdout.rstrip())
    if p.returncode != 0:
        print(p.stderr.rstrip())
        sys.exit(f"command failed: {args}")


def copy_tree(src, dst, keep=lambda fn: True):
    n = 0
    for root, _, files in os.walk(src):
        for fn in files:
            if not keep(fn):
                continue
            rel = os.path.relpath(os.path.join(root, fn), src)
            out = os.path.join(dst, rel)
            os.makedirs(os.path.dirname(out), exist_ok=True)
            shutil.copy(os.path.join(root, fn), out)
            n += 1
    return n


def main():
    install = "--install" in sys.argv

    # 1. collect the per-chunk translations back into the unit list
    us = json.load(open(os.path.join(WORK, "units.json"), encoding="utf-8"))
    out = os.path.join(WORK, "units_translated.json")
    U.collect(us, CHUNKS, out)
    us = json.load(open(out, encoding="utf-8"))

    todo = [u for u in us if U.needs_translation(u) and not u.get("dst")]
    if todo:
        print(f"!! {len(todo)} units still untranslated "
              f"(they will stay in the original language)")

    # 2. write the translations into the tl tree
    U.apply(TL_SRC, us, PROJ_TL)

    # 3. drop the patch script in and compile everything to .rpyc
    patch_files = [fn for fn in os.listdir(MOD_SRC) if fn.endswith(".rpy")]
    for fn in patch_files:
        shutil.copy(os.path.join(MOD_SRC, fn), os.path.join(PROJ, "game", fn))

    # 3a. Korean UI catalog -> zz_korean_ui.rpy (the game's l10n_ui() reads UI[<language>])
    run(sys.executable, os.path.join(TOOLS, "ui_catalog.py"), "build")
    ui = json.load(open(UI_KO, encoding="utf-8"))
    with open(os.path.join(PROJ, "game", "zz_korean_ui.rpy"), "w", encoding="utf-8") as f:
        f.write("# Generated by tools/build_mod.py from work/ui_korean.json\n\n"
                "init -19 python:\n"
                "    import obe_localization_catalog as _ko_catalog\n"
                f"    _ko_catalog.UI['korean'] = {ui!r}\n")
    patch_files.append("zz_korean_ui.rpy")
    print("compiling...")
    run(os.path.join(PROJ, "lib", "py3-windows-x86_64", "python.exe"),
        "OurBriefEternity.py", ".", "compile", cwd=PROJ)

    # 4. stage exactly the files the game needs
    if os.path.exists(STAGE):
        shutil.rmtree(STAGE)
    n = copy_tree(PROJ_TL, os.path.join(STAGE, "tl", "korean"),
                  keep=lambda fn: fn.endswith(".rpyc"))
    print(f"staged {n} compiled translation files")

    for fn in patch_files:
        rpyc = os.path.join(PROJ, "game", fn + "c")
        if not os.path.exists(rpyc):
            sys.exit(f"missing compiled patch: {rpyc}")
        shutil.copy(rpyc, os.path.join(STAGE, fn + "c"))
        print(f"staged {fn}c")

    # 4a. voice-drama / theme-song lyrics (audio/asmr/<n>.lrc). .lrc is looked up
    #     by *text* language, so tl/korean/audio/asmr/ wins when Korean is on.
    for name in sorted(os.listdir(os.path.join(W, "extracted", "audio", "asmr"))):
        if not name.endswith(".lrc"):
            continue
        stem = name[:-4]
        lyr = os.path.join(CHUNKS, f"lyrics_{stem}.out.json")
        if not os.path.exists(lyr):
            continue
        ko = {r["i"]: r["dst"] for r in json.load(open(lyr, encoding="utf-8")) if r.get("dst")}
        src = os.path.join(W, "extracted", "audio", "asmr", name)
        out, i = [], 0
        for line in open(src, encoding="utf-8-sig").read().splitlines():
            if line.startswith("[") and "]" in line:
                tag = line[:line.index("]") + 1]
                line = tag + ko.get(i, line[len(tag):].strip())
                i += 1
            out.append(line)
        dst = os.path.join(STAGE, "tl", "korean", "audio", "asmr", name)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        with open(dst, "w", encoding="utf-8") as f:
            f.write("\n".join(out) + "\n")
        print(f"staged {name} ({len(ko)}/{i} lines translated)")

    # 4b. translated images (tl/korean/<same path as original>), if any
    if os.path.isdir(IMG_SRC):
        n = copy_tree(IMG_SRC, os.path.join(STAGE, "tl", "korean"))
        print(f"staged {n} translated images")
    upd = os.path.join(UPD_IMG, "번역본")
    if os.path.isdir(upd):
        n = copy_tree(upd, os.path.join(STAGE, "tl", "korean"))
        print(f"staged {n} translated images from the 11-20 update batch")
    shared = os.path.join(UPD_IMG, "번역본_공용")
    if os.path.isdir(shared):
        n = copy_tree(shared, STAGE)
        print(f"staged {n} shared Korean buttons")
    for rel in KOR_BUTTONS:
        dst = os.path.join(STAGE, rel)
        if not os.path.exists(dst):
            # stand-in so the language screen does not error before the art is delivered
            src = os.path.join(W, "v1120", "img_new", rel.replace("_kor_", "_eng_"))
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy(src, dst)
            print(f"!! TEMPORARY stand-in (English art) for {rel}")

    # 4c. translated movies. The game plays "images/<name>.webm"; .webm is looked up
    #     by text language, so tl/korean/images/<name>.webm wins when Korean is on.
    if os.path.isdir(VID_SRC):
        n = copy_tree(VID_SRC, os.path.join(STAGE, "tl", "korean", "images"),
                      keep=lambda fn: fn.endswith(".webm"))
        print(f"staged {n} translated movies")

    # 5. optionally install
    if install:
        if not os.path.isdir(GAME):
            sys.exit(f"game folder not found: {GAME}")
        copied = copy_tree(STAGE, GAME)
        print(f"installed {copied} files -> {GAME}")
    else:
        print(f"\nstaged in {STAGE} (run with --install to copy into the game)")


if __name__ == "__main__":
    main()
